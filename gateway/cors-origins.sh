#!/bin/sh
# Turns CORS_ALLOWED_ORIGINS (comma-separated, from .env) into an nginx map (task A-23).
# Runs inside the gateway container before nginx starts (/docker-entrypoint.d/). An origin that is
# not exactly scheme://host[:port] is rejected, so nothing from .env can inject nginx configuration.
set -eu

OUT=/etc/nginx/conf.d/00-cors-origins.conf
ORIGINS="${CORS_ALLOWED_ORIGINS:-}"

{
  echo "# Generated by cors-origins.sh from CORS_ALLOWED_ORIGINS. Do not edit."
  echo 'map $http_origin $cors_origin {'
  echo '    default "";'
} > "$OUT"

count=0
for origin in $(echo "$ORIGINS" | tr ',' ' '); do
  if ! echo "$origin" | grep -Eq '^https?://[A-Za-z0-9.-]+(:[0-9]{1,5})?$'; then
    echo "cors-origins: refusing invalid origin '$origin'" >&2
    exit 1
  fi
  echo "    \"$origin\" \$http_origin;" >> "$OUT"
  count=$((count + 1))
done
echo "}" >> "$OUT"

echo "cors-origins: allowing $count origin(s)"
